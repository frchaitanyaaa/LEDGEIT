"""Apply numbered SQL migrations from apps/api/migrations (ADR-009).

Usage: python -m ledgeit_api.db.migrate [--url URL] [--dump infra/db/schema.sql]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from sqlalchemy import create_engine, text

from ..core.config import REPO_ROOT, get_settings

MIGRATIONS = REPO_ROOT / "apps" / "api" / "migrations"


def migration_files() -> list[Path]:
    return sorted(p for p in MIGRATIONS.glob("[0-9][0-9][0-9][0-9]_*.sql"))


def migrate(url: str | None = None, verbose: bool = True) -> list[str]:
    engine = create_engine(url or get_settings().database_url)
    applied_now: list[str] = []
    with engine.begin() as conn:
        conn.execute(text(
            "CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())"
        ))
        conn.execute(text("SELECT pg_advisory_xact_lock(4242)"))
        done = {r[0] for r in conn.execute(text("SELECT version FROM schema_migrations"))}
        for f in migration_files():
            if f.stem in done:
                continue
            if verbose:
                print(f"applying {f.name}")
            # raw cursor without params: psycopg runs multi-statement SQL and leaves % alone
            conn.connection.cursor().execute(f.read_text(encoding="utf-8"))
            conn.execute(text("INSERT INTO schema_migrations(version) VALUES (:v)"), {"v": f.stem})
            applied_now.append(f.stem)
    engine.dispose()
    return applied_now


def dump_reference(path: Path) -> None:
    parts = ["-- GENERATED by `python -m ledgeit_api.db.migrate --dump`. Reference copy only;",
             "-- the source of truth is apps/api/migrations/*.sql.", ""]
    for f in migration_files():
        parts += [f"-- ===== {f.name} =====", f.read_text(encoding="utf-8").rstrip(), ""]
    path.write_text("\n".join(parts) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url")
    ap.add_argument("--dump", help="write concatenated reference schema to this path and exit")
    a = ap.parse_args()
    if a.dump:
        dump_reference(Path(a.dump))
        print(f"wrote {a.dump}")
        return
    applied = migrate(a.url)
    print(f"migrations applied: {applied or 'none (up to date)'}")


if __name__ == "__main__":
    main()
